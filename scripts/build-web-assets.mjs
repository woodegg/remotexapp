import { spawnSync } from 'node:child_process';
import { cpSync, mkdtempSync, mkdirSync, readFileSync, readdirSync, rmSync, unlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const novncDir = path.join(projectRoot, 'third_party/novnc');
const novncUpstream = JSON.parse(readFileSync(path.join(novncDir, 'UPSTREAM.json'), 'utf8'));
const esbuild = process.env.ESBUILD || 'esbuild';
const outputDir = path.join(projectRoot, 'cmd/remotexappd/web/assets');
const temporaryDir = mkdtempSync(path.join(tmpdir(), 'remotexapp-assets.'));
const generatedURLs = path.join(projectRoot, 'cmd/remotexappd/web/sdk/generated-asset-urls.js');

function run(arguments_) {
  const result = spawnSync(esbuild, arguments_, { cwd:projectRoot, stdio:'inherit' });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`${esbuild} exited with status ${result.status}`);
}

function oneOutput(prefix) {
  const matches = readdirSync(temporaryDir).filter(name => name.startsWith(`${prefix}-`) && name.endsWith('.js'));
  if (matches.length !== 1) throw new Error(`expected one ${prefix} bundle, found ${matches.join(', ')}`);
  return matches[0];
}

try {
  run([
    'cmd/remotexappd/web/assets-src/novnc-entry.js',
    '--bundle', '--format=esm', '--minify', '--legal-comments=inline',
    `--alias:novnc-core=${path.join(novncDir, 'core')}`,
    '--entry-names=novnc-[hash]', `--outdir=${temporaryDir}`,
    '--banner:js=/*! noVNC bundle: Copyright the noVNC authors, MPL-2.0; bundled pako components retain their upstream MIT/Zlib terms. */',
  ]);
  const novncBundle = oneOutput('novnc');
  writeFileSync(generatedURLs,
    `// Generated by scripts/build-web-assets.mjs. Do not edit manually.\nexport const NOVNC_BUNDLE_URL = '/assets/${novncBundle}';\n`);

  run([
    'cmd/remotexappd/web/sdk/index.js',
    '--bundle', '--format=esm', '--minify', '--legal-comments=inline',
    '--entry-names=sdk-[hash]', `--outdir=${temporaryDir}`,
  ]);
  const sdkBundle = oneOutput('sdk');

  run([
    'cmd/remotexappd/web/console-src/index.js',
    '--bundle', '--format=esm', '--minify', '--legal-comments=inline',
    `--define:__REMOTEXAPP_CONSOLE_SDK__=${JSON.stringify('./' + sdkBundle)}`,
    '--entry-names=console-[hash]', `--outdir=${temporaryDir}`,
  ]);
  const consoleBundle = oneOutput('console');

  mkdirSync(outputDir, { recursive:true });
  for (const name of readdirSync(outputDir)) {
    if (/^(console|novnc|sdk)-.*\.js$/.test(name) || name === 'manifest.json') unlinkSync(path.join(outputDir, name));
  }
  cpSync(path.join(temporaryDir, novncBundle), path.join(outputDir, novncBundle));
  cpSync(path.join(temporaryDir, sdkBundle), path.join(outputDir, sdkBundle));
  cpSync(path.join(temporaryDir, consoleBundle), path.join(outputDir, consoleBundle));
  const manifest = {
    formatVersion:1,
    sdk:sdkBundle,
    console:consoleBundle,
    novnc:novncBundle,
    novncVersion:novncUpstream.version,
    novncCommit:novncUpstream.commit,
    novncArchiveSha256:novncUpstream.archiveSha256,
    esbuildVersion:spawnSync(esbuild, ['--version'], { encoding:'utf8' }).stdout.trim(),
  };
  writeFileSync(path.join(outputDir, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
  const sdkBytes = readFileSync(path.join(outputDir, sdkBundle)).length;
  const consoleBytes = readFileSync(path.join(outputDir, consoleBundle)).length;
  const novncBytes = readFileSync(path.join(outputDir, novncBundle)).length;
  if (novncBytes > 256 * 1024) {
    throw new Error(`noVNC bundle ${novncBytes} bytes exceeds the 256 KiB review budget`);
  }
  console.log(`web assets: ${sdkBundle} ${sdkBytes} bytes; ${consoleBundle} ${consoleBytes} bytes; ${novncBundle} ${novncBytes} bytes`);
} finally {
  rmSync(temporaryDir, { recursive:true, force:true });
}
