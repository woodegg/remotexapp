import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';

const output = 'docs/current-state.md';
const version = readFileSync('VERSION', 'utf8').trim();
const sdkVersion = JSON.parse(readFileSync('cmd/remotexappd/web/sdk/package.json', 'utf8')).version;
const upstream = JSON.parse(readFileSync('third_party/novnc/UPSTREAM.json', 'utf8'));
const goMod = readFileSync('go.mod', 'utf8');
const goVersion = goMod.match(/^go (\S+)$/m)?.[1];
const toolchain = goMod.match(/^toolchain (\S+)$/m)?.[1];
if (!goVersion || !toolchain) throw new Error('go.mod must declare go and toolchain versions');

const apps = readdirSync('apps', { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && existsSync(`apps/${entry.name}/manifest.json`))
  .map((entry) => JSON.parse(readFileSync(`apps/${entry.name}/manifest.json`, 'utf8')))
  .sort((left, right) => left.id.localeCompare(right.id));
const abiVersions = [...new Set(apps.map((app) => app.apiVersion))];
if (abiVersions.length !== 1) throw new Error(`App Packages disagree on apiVersion: ${abiVersions.join(', ')}`);

const rows = apps.map((app) => `| \`${app.id}\` | ${app.name} | \`${app.driverVersion}\` | ${app.runMode} | ${app.singleton ? 'yes' : 'no'} |`).join('\n');
const content = `# Current Repository State

<!-- Generated by scripts/generate-current-state.mjs; do not edit manually. -->

This page is the concise source-tree identity. It intentionally does not infer
live deployment state; use the latest approved alignment evidence for that.

| Component | Current identity |
|---|---|
| RemoteXApp core | \`${version}\` |
| Browser SDK | \`${sdkVersion}\` |
| App Package ABI | \`${abiVersions[0]}\` |
| Go language/toolchain | \`${goVersion}\` / \`${toolchain}\` |
| Vendored noVNC | \`${upstream.release}\` at \`${upstream.commit.slice(0, 12)}\` |

## Shipped App Packages

| ID | Name | Driver version | Run mode | Singleton |
|---|---|---:|---|---|
${rows}

## Authoritative Sources

- Core version: \`VERSION\`
- SDK version: \`cmd/remotexappd/web/sdk/package.json\`
- App identities: \`apps/*/manifest.json\`
- noVNC provenance: \`third_party/novnc/UPSTREAM.json\`
- Accepted behavior: \`docs/requirements.md\`
- Live fleet identity: latest authorized alignment evidence under
  \`tests/go-live-validation/results/\`
`;

if (process.argv.includes('--check')) {
  if (!existsSync(output) || readFileSync(output, 'utf8') !== content) {
    throw new Error(`${output} is stale; run node scripts/generate-current-state.mjs`);
  }
} else {
  writeFileSync(output, content);
  console.log(`generated ${output}`);
}
